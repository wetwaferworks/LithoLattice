static unsigned lk_flags(int c) {
  if (c < 0) {
    /* The documented domain promise (include/ctype.h): every
     * negative classifies as the byte with the same low eight
     * bits. The old floor at -128 silently broke that promise
     * for values like -191 (audit finding A-2). EOF (-1) lands
     * on 0xff, whose entry is empty, exactly as documented. */
    c &= 0xff;
  } else if (c > 255) {
    return 0;
  }
  return lk_ctype_flags[c];
}

int isupper(int c) { return (lk_flags(c) & LK_UPPER) != 0; }
int islower(int c) { return (lk_flags(c) & LK_LOWER) != 0; }
int isalpha(int c) { return (lk_flags(c) & (LK_UPPER | LK_LOWER)) != 0; }
int isdigit(int c) { return (lk_flags(c) & LK_DIGIT) != 0; }
int isalnum(int c) {
  return (lk_flags(c) & (LK_UPPER | LK_LOWER | LK_DIGIT)) != 0;
}
int isxdigit(int c) { return (lk_flags(c) & LK_XDIGIT) != 0; }
int isspace(int c) { return (lk_flags(c) & LK_SPACE) != 0; }
int isblank(int c) { return (lk_flags(c) & LK_BLANK) != 0; }
int iscntrl(int c) { return (lk_flags(c) & LK_CNTRL) != 0; }
int isprint(int c) { return (lk_flags(c) & LK_PRINT) != 0; }
int isgraph(int c) { return (lk_flags(c) & LK_GRAPH) != 0; }
int ispunct(int c) { return (lk_flags(c) & LK_PUNCT) != 0; }

int tolower(int c) {
  if (c >= 'A' && c <= 'Z') return c + ('a' - 'A');
  return c;
}

int toupper(int c) {
  if (c >= 'a' && c <= 'z') return c - ('a' - 'A');
  return c;
}
