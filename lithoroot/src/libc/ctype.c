/* ctype.c ... LithoLibC character classification, C locale only.
 *
 * One flag table over the byte range, derived mechanically from
 * the class definitions repeated in the comment above it, so the
 * table can be re-derived and checked instead of trusted. Bytes at
 * or above 0x80 carry no flags in the C locale, which is what the
 * long run of zero rows says.
 *
 * Input handling follows the promise in ctype.h: the accessor maps
 * a negative input to the byte with the same low eight bits before
 * consulting the table (EOF, -1, lands on byte 0xff, whose entry is
 * zero, so EOF classifies as nothing, exactly as required), and
 * inputs below -128 or above 255 classify as nothing. The case
 * conversions special-case only their letter ranges and return
 * every other input unchanged, EOF included.
 */

#include <ctype.h>

#define LK_UPPER 0x001u
#define LK_LOWER 0x002u
#define LK_DIGIT 0x004u
#define LK_SPACE 0x008u
#define LK_PUNCT 0x010u
#define LK_CNTRL 0x020u
#define LK_XDIGIT 0x040u
#define LK_BLANK 0x080u
#define LK_PRINT 0x100u
#define LK_GRAPH 0x200u

