// Generates the Nemo View depth-band table (engine/src/render/include/litholattice/render/nemo_view_depth_bands.h).
// Run once offline; the output is checked in, so no runtime float math decides a band.
// Usage: nemo_view_lut_gen > nemo_view_depth_bands.h
// Mirrors swsimd::depthQ and depthRemap (software_simd.h) for each remap mode and the
// game camera's clip range (near 0.05, far 1000). Build without fast-math or FMA contraction.
#include <cmath>
#include <cstdint>
#include <cstdio>
#include <cstring>

static float depthRecip(float d) {
  float u = 1.0f - d;
  u = u < 3.0517578125e-05f ? 3.0517578125e-05f : u;
  uint32_t b;
  std::memcpy(&b, &u, 4);
  return float(int32_t(0x3F800000u - b)) * (1.0f / (15.0f * 8388608.0f));
}
static float remap(int mode, float d) { return mode == 1 ? 1.0f - std::sqrt(1.0f - d) : mode == 2 ? depthRecip(d) : d; }
static uint16_t depthQ(int mode, float d) {
  d = d < 0.0f ? 0.0f : (d > 1.0f ? 1.0f : d);
  d = remap(mode, d);
  return uint16_t(std::nearbyintf(d * 65535.0f));
}

int main() {
  const float zn = 0.05f, zf = 1000.0f;
  const float m10 = (zf + zn) / (zn - zf), m14 = 2.f * zf * zn / (zn - zf);
  const float edges[6] = {1.f, 2.f, 3.f, 4.f, 6.f, 10.f};  // band edges in blocks of view depth
  std::printf("// Generated by tools/nemo_view_lut_gen.cpp. Do not edit by hand.\n");
  std::printf("// Depth-band edges as 16-bit depth codes for near 0.05 / far 1000, one row per\n");
  std::printf("// LL_SW_DEPTH_REMAP mode (0 linear, 1 sqrt, 2 reciprocal). Band = number of edges a\n");
  std::printf("// code is above; 0xFFFF (cleared, nothing drawn) is band 7, sky.\n");
  std::printf("#pragma once\n#include <cstdint>\n\nnamespace litholattice::nemoview {\n\n");
  std::printf("inline constexpr uint16_t kDepthBandEdges[3][6] = {\n");
  for (int mode = 0; mode < 3; ++mode) {
    std::printf("    {");
    for (int k = 0; k < 6; ++k) {
      const float w = edges[k];
      const float z = (m10 * (-w) + m14) / w;
      std::printf("%u%s", unsigned(depthQ(mode, z)), k < 5 ? ", " : "");
    }
    std::printf("},\n");
  }
  std::printf("};\n\n}  // namespace litholattice::nemoview\n");
  return 0;
}
